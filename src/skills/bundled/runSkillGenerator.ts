import { registerBundledSkill } from '../bundledSkills.js'

const RUN_PROMPT = `# Run

Launch this project's app and drive it so a change can be seen working, not just compiled.

1. If \`.claude/skills/run/SKILL.md\` exists, follow it exactly — it is this project's recorded launch recipe (build step, start command, readiness signal, URL/entry point, how to stop). If it does not exist, run \`/run-skill-generator\` first, then continue.
2. Start the app in the background (\`run_in_background: true\`), wait for the readiness line, and report the URL or entry point.
3. Do what the user asked with it (open the page in the browser tools if any are loaded, hit the endpoint, run the command) and report what you actually observed.
4. Leave it running only if the user asked for that; otherwise stop it and say so.
`

const GENERATOR_PROMPT = `# Run-skill generator

Teach \`/run\` and \`/verify\` how to build, launch and check *this* project by writing a project-local skill.

## Investigate (read-only)

Look at, in order: \`package.json\` scripts and \`packageManager\`, \`Makefile\`/\`justfile\`, \`Dockerfile\`/\`compose.yaml\`, \`pyproject.toml\`/\`requirements.txt\`, \`Cargo.toml\`, \`go.mod\`, \`README\` (install / run / test sections), CI workflows (\`.github/workflows/*.yml\` show the real build + test commands), and any \`.env.example\`. Identify:
- **build** command (or none)
- **start** command for the dev server / CLI entry, and the **readiness signal** (log line, port, or file)
- **URL / entry point** to exercise, and any required env vars or fixtures
- **test** and **lint** commands
- how to **stop** it cleanly

Actually run the start command once in the background to confirm the readiness signal, then stop it. If it fails, record the failure and the fix instead of guessing.

## Write the skill

Create \`.claude/skills/run/SKILL.md\` with this frontmatter and body (adapt, don't pad):

\`\`\`markdown
---
name: run
description: How to build, launch and reach this project's app (generated by /run-skill-generator)
---
## Build
<command or "none">
## Start
<command>  — ready when: <log line / port>
## Reach
<URL or CLI usage>
## Verify quickly
<2–4 commands with expected output>
## Stop
<command or signal>
## Gotchas
<env vars, ports, fixtures, first-run steps>
\`\`\`

Keep it under 60 lines. Then print the file back to the user and say that \`/run\` and \`/verify\` will use it from now on.
`

export function registerRunSkill(): void {
  registerBundledSkill({
    name: 'run',
    description: "Launch and drive this project's app to see a change working",
    userInvocable: true,
    async getPromptForCommand(args) {
      return [
        {
          type: 'text',
          text: args
            ? `${RUN_PROMPT}\n\n## User request\n\n${args}`
            : RUN_PROMPT,
        },
      ]
    },
  })
}

export function registerRunSkillGeneratorSkill(): void {
  registerBundledSkill({
    name: 'run-skill-generator',
    description:
      'Teach /run and /verify how to build and launch this project by writing .claude/skills/run/SKILL.md',
    userInvocable: true,
    async getPromptForCommand(args) {
      return [
        {
          type: 'text',
          text: args
            ? `${GENERATOR_PROMPT}\n\n## Hints from the user\n\n${args}`
            : GENERATOR_PROMPT,
        },
      ]
    },
  })
}
